import sharp from 'sharp';
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

// Homepage marquee tiles are 158x72 CSS px; 316x144 covers 2x DPR. Writes a
// WebP to public/landing/logos/opt/ ONLY where it beats the original (big SVGs
// with embedded rasters, un-paletted PNGs), and lists those in
// lib/data/client-logos-webp.ts so the row can pick the smaller file.
const DIR = 'public/landing/logos', OUT = path.join(DIR, 'opt');
await mkdir(OUT, { recursive: true });
const better = [];
let before = 0, after = 0;
for (const file of (await readdir(DIR)).sort()) {
  const ext = path.extname(file).toLowerCase();
  if (!ext) continue;
  const src = await readFile(path.join(DIR, file));
  const out = await sharp(src, { density: ext === '.svg' ? 300 : 72, failOn: 'none' })
    .resize({ width: 316, height: 144, fit: 'inside', withoutEnlargement: ext !== '.svg' })
    .webp({ quality: 82, alphaQuality: 90, effort: 6 })
    .toBuffer();
  before += src.length;
  if (out.length < src.length * 0.9) {
    await writeFile(path.join(OUT, file.replace(/\.[^.]+$/, '.webp')), out);
    better.push(file);
    after += out.length;
  } else after += src.length;
}
await writeFile('lib/data/client-logos-webp.ts',
  `// Generated by scripts/optimize-client-logos-webp.mjs — do not edit by hand.\n` +
  `// Client logos that have a smaller WebP in public/landing/logos/opt/.\n` +
  `export const clientLogosWebp = new Set<string>(${JSON.stringify(better, null, 2)});\n`);
console.log(`${better.length} logos -> webp; ${(before/1024).toFixed(0)}KB -> ${(after/1024).toFixed(0)}KB`);
